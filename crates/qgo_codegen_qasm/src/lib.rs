//! `qgo_codegen_qasm`: Pass 5.1 OpenQASM 3.0 emitter.
//! Emits valid `OPENQASM 3.0; include "stdgates.inc";` code with native `qubit[N]`, `bit`,
//! `ctrl @`, `inv @`, `if`, and `while` constructs.

use std::collections::BTreeSet;
use qgo_mir::{MirFunc, MirGateKind, MirModule, MirStmt, QubitWire};
use qgo_opt::flatten_conjugates;

/// Emits an OpenQASM 3.0 program string for an entire [`MirModule`].
pub fn emit_qasm3(module: &MirModule) -> String {
    let mut out = String::new();
    out.push_str("// Generated by QGo Compiler (OpenQASM 3.0 Backend)\n");
    out.push_str(&format!("// Package: {}\n", module.package));
    out.push_str("OPENQASM 3.0;\n");
    out.push_str("include \"stdgates.inc\";\n\n");

    for func in &module.funcs {
        emit_func_qasm3(func, &mut out);
        out.push('\n');
    }
    out
}

fn emit_func_qasm3(func: &MirFunc, out: &mut String) {
    out.push_str(&format!(
        "// Function: {} (purity: {})\n",
        func.name, func.purity
    ));

    let mut declared_regs = BTreeSet::new();
    for p in &func.params {
        if p.is_quantum {
            out.push_str(&format!("qubit[{}] {};\n", p.width.max(1), p.name));
            declared_regs.insert(p.name.clone());
        }
    }

    let flat_body = flatten_conjugates(&func.body);
    emit_stmts_qasm3(&flat_body, 0, &mut declared_regs, out);
}

fn emit_stmts_qasm3(
    stmts: &[MirStmt],
    indent: usize,
    declared_regs: &mut BTreeSet<String>,
    out: &mut String,
) {
    let pad = "    ".repeat(indent);
    for stmt in stmts {
        match stmt {
            MirStmt::QAlloc { reg, size, .. } => {
                if declared_regs.insert(reg.clone()) {
                    out.push_str(&format!("{}qubit[{}] {};\n", pad, (*size).max(1), reg));
                }
                for i in 0..(*size).max(1) {
                    out.push_str(&format!("{}reset {}[{}];\n", pad, reg, i));
                }
            }
            MirStmt::QFree { reg, size } => {
                out.push_str(&format!(
                    "{}// ancilla `{}` ({} qubit(s)) verified uncomputed to |0>\n",
                    pad, reg, size
                ));
            }
            MirStmt::Gate {
                kind,
                controls,
                targets,
            } => {
                emit_gate_qasm3(kind, controls, targets, &pad, out);
            }
            MirStmt::Measure { qubit, dst_var } => {
                out.push_str(&format!(
                    "{}bit {} = measure {};\n",
                    pad,
                    dst_var,
                    format_wire(qubit)
                ));
            }
            MirStmt::Reset { qubit } => {
                out.push_str(&format!("{}reset {};\n", pad, format_wire(qubit)));
            }
            MirStmt::ClassicalIf {
                cond_var,
                then_body,
                else_body,
            } => {
                out.push_str(&format!("{}if ({} == 1) {{\n", pad, cond_var));
                emit_stmts_qasm3(then_body, indent + 1, declared_regs, out);
                if !else_body.is_empty() {
                    out.push_str(&format!("{}}} else {{\n", pad));
                    emit_stmts_qasm3(else_body, indent + 1, declared_regs, out);
                }
                out.push_str(&format!("{}}}\n", pad));
            }
            MirStmt::While { cond_var, body } => {
                out.push_str(&format!("{}while ({} == 1) {{\n", pad, cond_var));
                emit_stmts_qasm3(body, indent + 1, declared_regs, out);
                out.push_str(&format!("{}}}\n", pad));
            }
            _ => {}
        }
    }
}

fn emit_gate_qasm3(
    kind: &MirGateKind,
    controls: &[QubitWire],
    targets: &[QubitWire],
    pad: &str,
    out: &mut String,
) {
    let mut all_wires: Vec<String> = controls.iter().map(format_wire).collect();
    all_wires.extend(targets.iter().map(format_wire));
    let wires_str = all_wires.join(", ");

    // Special-case standard 1/2-control X and 1-control Phase gates for idiomatic stdgates.inc
    if matches!(kind, MirGateKind::X) {
        match controls.len() {
            0 => {
                out.push_str(&format!("{}x {};\n", pad, wires_str));
                return;
            }
            1 => {
                out.push_str(&format!("{}cx {};\n", pad, wires_str));
                return;
            }
            2 => {
                out.push_str(&format!("{}ccx {};\n", pad, wires_str));
                return;
            }
            n => {
                out.push_str(&format!("{}ctrl({}) @ x {};\n", pad, n, wires_str));
                return;
            }
        }
    }

    let base_op = match kind {
        MirGateKind::X => "x".to_owned(),
        MirGateKind::Y => "y".to_owned(),
        MirGateKind::Z => "z".to_owned(),
        MirGateKind::H => "h".to_owned(),
        MirGateKind::S => "s".to_owned(),
        MirGateKind::Sdg => "sdg".to_owned(),
        MirGateKind::T => "t".to_owned(),
        MirGateKind::Tdg => "tdg".to_owned(),
        MirGateKind::Rx(theta) => format!("rx({:.8})", theta),
        MirGateKind::Ry(theta) => format!("ry({:.8})", theta),
        MirGateKind::Rz(theta) => format!("rz({:.8})", theta),
        MirGateKind::Phase(theta) => format!("p({:.8})", theta),
        MirGateKind::Swap => "swap".to_owned(),
    };

    if controls.is_empty() {
        out.push_str(&format!("{}{} {};\n", pad, base_op, wires_str));
    } else if controls.len() == 1 {
        out.push_str(&format!("{}ctrl @ {} {};\n", pad, base_op, wires_str));
    } else {
        out.push_str(&format!(
            "{}ctrl({}) @ {} {};\n",
            pad,
            controls.len(),
            base_op,
            wires_str
        ));
    }
}

fn format_wire(w: &QubitWire) -> String {
    format!("{}[{}]", w.reg, w.index)
}

#[cfg(test)]
mod tests {
    use super::*;
    use qgo_hir::check_module;
    use qgo_mir::lower_to_mir;
    use qgo_opt::{optimize_module, SynthMode};
    use qgo_span::FileId;
    use qgo_syntax::parse_source;

    #[test]
    fn test_emit_openqasm3_with_conjugation() {
        let src = r#"package teleport
func BellPair(q qreg[2]) unitary {
    H(q[0])
    CX(q[0], q[1])
}
"#;
        let (ast, _) = parse_source(FileId(0), src);
        let (hir, diags) = check_module(&ast);
        assert!(diags.is_empty());
        let mut mir = lower_to_mir(&hir);
        optimize_module(&mut mir, SynthMode::Width);
        let qasm = emit_qasm3(&mir);
        assert!(qasm.contains("OPENQASM 3.0;"));
        assert!(qasm.contains("include \"stdgates.inc\";"));
        assert!(qasm.contains("h q[0];"));
        assert!(qasm.contains("cx q[0], q[1];"));
    }
}
